using Wpf.Ui.Controls;

namespace StudComp.Resources;

/// <summary>Раздел, по которому вызвана справка. Значения – только для выбора набора тем.</summary>
public enum HelpSection
{
    Archivist,
    Organizer,
    ReportForge,
    Cards,
    SubjectHub,
    DeadlineWork,
}

/// <summary>Один пункт справки: короткий заголовок и одна-две фразы по делу.</summary>
public sealed record HelpPoint(string Title, string Text);

/// <summary>
/// Тема помощника – либо «О разделе», либо одна подвкладка.
/// </summary>
/// <param name="Title">Название темы; для подвкладок совпадает с надписью на вкладке.</param>
/// <param name="Icon">
/// Глиф для рельса тем. Именно перечисление, а не строка: опечатка в имени иконки тогда не
/// соберётся вовсе, вместо того чтобы молча отрисоваться пустотой.
/// </param>
/// <param name="Lead">Одна фраза: зачем это нужно.</param>
/// <param name="Points">Как этим пользоваться, 3–5 пунктов.</param>
public sealed record HelpTopic(string Title, SymbolRegular Icon, string Lead, IReadOnlyList<HelpPoint> Points);

/// <summary>
/// Тексты помощника по разделам. Живут в App-слое, потому что это текст интерфейса – как
/// <see cref="AppDateFormat"/>, <see cref="RussianPlural"/> и <see cref="RelativeDayFormatter"/>.
/// </summary>
/// <remarks>
/// Темы перечислены в <b>физическом порядке вкладок</b> соответствующей страницы, поэтому
/// <c>SelectedTabIndex</c> – прямой индекс в список (после нулевой темы «О разделе»). Это важно для
/// Хаба предмета: порядок значений <c>SubjectHubTab</c> намеренно не совпадает с порядком вкладок на
/// экране, и обратной карты индекс→enum в проекте нет.
/// При добавлении или перестановке вкладки править здесь же – иначе помощник откроется не на той теме.
/// Содержимое статично, поэтому класс без состояния и зависимостей.
