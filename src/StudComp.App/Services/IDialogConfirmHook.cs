namespace StudComp.Services;

/// <summary>
/// Вьюмодель формы, которой нужно что-то сделать <b>в момент подтверждения</b> диалога, пока её
/// разметка ещё в дереве и уже размечена.
/// </summary>
/// <remarks>
/// Заведено ради снимка холста рисования: <c>RenderTargetBitmap</c> по неразмеченному или уже
/// снятому с экрана элементу даёт пустую картинку, а делать снимок на каждое изменение (как было)
/// — это полный рендер и PNG-кодирование в UI-потоке на каждый штрих и на каждый задетый ластиком
/// штрих. Хук вызывается из <see cref="IDialogService.ShowEditorAsync"/> по событию закрытия.
/// </remarks>
public interface IDialogConfirmHook
{
    /// <summary>Диалог подтверждают. Исключения отсюда наружу не выпускаются.</summary>
    void OnConfirming();
}
