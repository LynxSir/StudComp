using StudComp.Core.Domain;

namespace StudComp.ViewModels;

/// <summary>Одна строка шпаргалки: как написать, что получится и когда это нужно.</summary>
public sealed record MarkdownHelpRow(string Syntax, string Result, string Description);

/// <summary>Раздел шпаргалки — просто заголовок и несколько строк.</summary>
public sealed record MarkdownHelpSection(string Title, IReadOnlyList<MarkdownHelpRow> Rows);

/// <summary>Одна строка справочника символов: команда с обратной косой и её глиф.</summary>
public sealed record MathSymbolHelpRow(string Command, string Glyph);

/// <summary>Группа справочника символов («Греческие строчные», «Стрелки»…).</summary>
public sealed record MathSymbolHelpGroup(string Title, IReadOnlyList<MathSymbolHelpRow> Rows);

