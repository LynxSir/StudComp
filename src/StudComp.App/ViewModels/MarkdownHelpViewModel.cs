    public IReadOnlyList<MathSymbolHelpGroup> SymbolGroups { get; } = MathExpression.Catalog
        .GroupBy(x => x.Group)
        .Select(group => new MathSymbolHelpGroup(
            group.Key,
            group.Select(x => new MathSymbolHelpRow("\\" + x.Name, x.Glyph)).ToArray()))
        .ToArray();
