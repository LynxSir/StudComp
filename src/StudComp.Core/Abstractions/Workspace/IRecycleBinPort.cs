namespace StudComp.Core.Abstractions.Workspace;

/// <summary>
/// Единственное место во всём приложении, где файл может покинуть диск, — и только переездом в
/// «Корзину» Windows, откуда его вернёт сам пользователь средствами системы.
/// </summary>
/// <remarks>
/// В <c>IFileSystem</c> удаления нет и не будет: отсутствие операции в абстракции и есть самая
/// дешёвая гарантия сохранности пользовательских файлов (ARCHITECTURE §14, ADR §16.30). Этот порт
/// её не отменяет, а очерчивает: он умеет только «в корзину» и «убрать пустую папку», причём
/// второе неспособно уничтожить данные по построению — непустой каталог оно не тронет.
/// <para>
/// Реализация живёт в App-слое: API корзины Windows-only, а <c>Infrastructure</c> собирается под
/// платформенно-нейтральный <c>net10.0</c> (тот же довод, что у ADR §16.16 и Win32-интеропа
/// <c>GlobalHotkeyService</c>).
/// </para>
/// </remarks>
public interface IRecycleBinPort
{
    /// <summary>
    /// Отправить файл в «Корзину». <see langword="false"/> — файла нет, он занят, либо на этом томе
    /// корзины не бывает (сетевой или съёмный диск). Исключений не бросает.
    /// </summary>
    /// <remarks>
    /// Отказ всегда означает «файл остался на месте» и никогда «файл удалён»: вызывающий обязан
    /// оставить его там, где он лежит, а не искать другой способ удаления.
    /// </remarks>
    bool TrySendToRecycleBin(string path);

    /// <summary>
    /// Убрать пустой каталог, который создало само приложение. Непустой каталог не удаляется —
    /// это свойство реализации, а не проверка вызывающего.
    /// </summary>
    bool TryRemoveEmptyDirectory(string path);
}
