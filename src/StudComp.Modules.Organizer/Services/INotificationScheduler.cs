namespace StudComp.Modules.Organizer.Services;

/// <summary>
/// Единая точка планирования напоминаний Органайзера (ARCHITECTURE §9.5): один фоновый воркер
/// считает ближайшее событие (пара/дедлайн) и спит до него, а не опрашивает БД по таймеру.
/// </summary>
public interface INotificationScheduler
{
    /// <summary>
    /// Разбудить воркер, чтобы он пересчитал ближайшее напоминание сейчас — вызывать после изменения
    /// расписания/дедлайнов, чтобы новые события не ждали конца текущего сна.
    /// </summary>
    void RequestReschedule();
}
